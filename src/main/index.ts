/** How long (ms) to wait after the last page-load event before checking for a CAPTCHA. */
const SETTLE_MS = 3000
/** After no CAPTCHA is found, how long to wait for a stream URL before giving up. */
const STREAM_WAIT_MS = 10000
/** After a stream URL is intercepted, how long to wait for cookies to settle. */
const STREAM_SETTLE_MS = 1500

const VINOVO_UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

/**
 * Headless VINOVO stream extraction — no browser window needed.
 * Stage-1 API accepts an empty reCAPTCHA response, so we can call it directly.
 */
async function fetchVinovoStream(embedUrl: string): Promise<{ streamUrl: string; headers: string[] } | null> {
  const fileCode = /\/e\/([a-zA-Z0-9]+)/.exec(embedUrl)?.[1]
  if (!fileCode) return null

  const pageResp = await net.fetch(embedUrl, { headers: { 'User-Agent': VINOVO_UA } })
  if (!pageResp.ok) return null
  const html = await pageResp.text()

  const csrfToken = /<meta name="token" content="([^"]+)"/.exec(html)?.[1]
  const cdnHost = /(https:\/\/[^/]+\.vincdn\.net)\//.exec(html)?.[1]
  if (!csrfToken || !cdnHost) return null

  const apiResp = await net.fetch(`https://vinovo.to/api/file/url/${fileCode}`, {
    method: 'POST',
    headers: {
      'User-Agent': VINOVO_UA,
      'Content-Type': 'application/x-www-form-urlencoded',
      'X-Requested-With': 'XMLHttpRequest',
      'Referer': embedUrl,
      'Origin': 'https://vinovo.to',
    },
    body: `recaptcha=&token=${encodeURIComponent(csrfToken)}`,
  })
  if (!apiResp.ok) return null

  const data = await apiResp.json() as { status: string; token?: string }
  if (data.status !== 'ok' || !data.token) return null

  return {
    streamUrl: `${cdnHost}/stream/${data.token}`,
    headers: [`Referer:${embedUrl}`, `Origin:https://vinovo.to`],
  }
}

interface CaptchaResult {
  cookieFile: string
  streamUrl?: string
  streamHeaders: string[]
}

async function openCaptchaWindow(captchaUrl: string, cookieFilePath: string): Promise<CaptchaResult> {
  return new Promise((resolve) => {
    const partition = `captcha-${Date.now()}`
    const ses = session.fromPartition(partition, { cache: false })
    const captchaHost = new URL(captchaUrl).hostname

    let done = false
    let windowShown = false
    let interceptedStreamUrl: string | undefined
    let interceptedStreamHeaders: string[] = []

    let settleTimer: NodeJS.Timeout | null = null
    let streamSettleTimer: NodeJS.Timeout | null = null
    let noStreamTimer: NodeJS.Timeout | null = null

    // Cache request headers so onHeadersReceived can correlate them by URL.
    const reqHeadersCache = new Map<string, Record<string, string>>()

    // Start hidden; shown only when a human CAPTCHA requires manual solving.
    const win = new BrowserWindow({
      width: 1024,
      height: 768,
      title: 'Solving CAPTCHA… — Video Downloader',
      autoHideMenuBar: true,
      show: false,
      webPreferences: {
        session: ses,
        contextIsolation: true,
        nodeIntegration: false
      }
    })

    const finish = (): void => {
      if (done) return
      done = true
      if (settleTimer) clearTimeout(settleTimer)
      if (streamSettleTimer) clearTimeout(streamSettleTimer)
      if (noStreamTimer) clearTimeout(noStreamTimer)
      ses.cookies
        .get({})
        .then((cookies) => writeNetscapeCookies(cookieFilePath, cookies))
        .catch(() => writeFileSync(cookieFilePath, '# Netscape HTTP Cookie File\n', 'utf8'))
        .finally(() => {
          resolve({ cookieFile: cookieFilePath, streamUrl: interceptedStreamUrl, streamHeaders: interceptedStreamHeaders })
          if (!win.isDestroyed()) win.destroy()
        })
    }

    const onStreamFound = (url: string, reqHeaders: Record<string, string>): void => {
      if (interceptedStreamUrl) return
      interceptedStreamUrl = url
      const headers: string[] = []
      const ref = reqHeaders['Referer'] ?? reqHeaders['referer'] ?? captchaUrl
      if (ref) headers.push(`Referer:${ref}`)
      const origin = reqHeaders['Origin'] ?? reqHeaders['origin']
      if (origin) headers.push(`Origin:${origin}`)
      interceptedStreamHeaders = headers
      if (noStreamTimer) { clearTimeout(noStreamTimer); noStreamTimer = null }
      if (streamSettleTimer) clearTimeout(streamSettleTimer)
      // Brief delay so cookies set by the stream request also land before we finish.
      streamSettleTimer = setTimeout(finish, STREAM_SETTLE_MS)
    }

    // Attach CDP debugger to read JSON response bodies from the page's own requests.
    // This works even when the API requires a CSRF token that only the page has.
    try {
      win.webContents.debugger.attach('1.3')
      void win.webContents.debugger.sendCommand('Network.enable', {})
      win.webContents.debugger.on('message', (_event, method, params: Record<string, unknown>) => {
        if (method !== 'Network.responseReceived' || interceptedStreamUrl) return
        const response = params.response as { url?: string; mimeType?: string } | undefined
        if (!response) return
        const url = response.url ?? ''
        const ct = (response.mimeType ?? '').toLowerCase()
        // HLS/DASH picked up by MIME type (belt-and-braces alongside onHeadersReceived)
        if (/x-mpegurl|mpegurl|dash\+xml/.test(ct)) {
          onStreamFound(url, {})
          return
        }
        // JSON on same host — read the actual body via CDP (no CSRF issue)
        if (!/json/.test(ct)) return
        try { if (new URL(url).hostname !== captchaHost) return } catch { return }
        const requestId = params.requestId as string
        void win.webContents.debugger
          .sendCommand('Network.getResponseBody', { requestId })
          .then((result: unknown) => {
            if (interceptedStreamUrl) return
            const body = (result as { body?: string }).body ?? ''
            try {
              const parsed = JSON.parse(body) as unknown
              const streamUrl = findStreamUrlInJson(parsed)
              if (streamUrl) {
                onStreamFound(streamUrl, { Referer: captchaUrl })
              } else if (
                parsed !== null && typeof parsed === 'object' &&
                (parsed as Record<string, unknown>).status === 'ok'
              ) {
                // API returned a token but no stream URL — click play to trigger the stream request.
                setTimeout(() => {
                  if (interceptedStreamUrl || done || win.isDestroyed()) return
                  void win.webContents.executeJavaScript(
                    `document.querySelector('.vjs-big-play-button')?.click()`
                  ).catch(() => {})
                }, 500)
              }
            } catch {}
          })
          .catch(() => {})
      })
    } catch {}

    // 1. URL-pattern interception: catch m3u8/mpd by URL path.
    ses.webRequest.onBeforeSendHeaders({ urls: ['<all_urls>'] }, (details, callback) => {
      reqHeadersCache.set(details.url, details.requestHeaders)
      if (!interceptedStreamUrl && /\.(m3u8|mpd)(\?|$)/i.test(details.url)) {
        onStreamFound(details.url, details.requestHeaders)
      }
      callback({ requestHeaders: details.requestHeaders })
    })

    // 2. Content-type interception: catch HLS/DASH served without a file extension.
    ses.webRequest.onHeadersReceived({ urls: ['<all_urls>'] }, (details, callback) => {
      if (!interceptedStreamUrl) {
        const ct = (
          details.responseHeaders?.['content-type']?.[0] ??
          details.responseHeaders?.['Content-Type']?.[0] ??
          ''
        ).toLowerCase()
        if (/application\/x-mpegurl|application\/vnd\.apple\.mpegurl|application\/dash\+xml/.test(ct)) {
          onStreamFound(details.url, reqHeadersCache.get(details.url) ?? {})
        }
      }
      callback({ responseHeaders: details.responseHeaders })
    })

    const checkAfterSettle = (): void => {
      if (settleTimer) clearTimeout(settleTimer)
      settleTimer = setTimeout(async () => {
        if (done || win.isDestroyed()) return
        if (interceptedStreamUrl) return

        // 3. DOM inspection: read stream URL from video elements / player APIs / inline scripts.
        try {
          const domUrl = (await win.webContents.executeJavaScript(FIND_STREAM_URL_JS)) as string | null
          if (domUrl) {
            onStreamFound(domUrl, { Referer: captchaUrl })
            return
          }
        } catch {}

        // 4. Check for a human CAPTCHA that still needs solving.
        try {
          const hasCaptcha = (await win.webContents.executeJavaScript(DETECT_CAPTCHA_JS)) as boolean
          if (hasCaptcha) {
            if (!windowShown) {
              windowShown = true
              win.setTitle('Solve CAPTCHA — Video Downloader')
              win.show()
            }
            void win.webContents.executeJavaScript(CAPTCHA_BANNER_JS)
            // Stream will arrive once the user solves the CAPTCHA.
          } else {
            // No CAPTCHA, no stream yet — keep waiting up to STREAM_WAIT_MS.
            if (noStreamTimer) clearTimeout(noStreamTimer)
            noStreamTimer = setTimeout(finish, STREAM_WAIT_MS)
          }
        } catch {
          finish()
        }
      }, SETTLE_MS)
    }

    win.webContents.on('did-finish-load', checkAfterSettle)
    win.webContents.on('did-navigate-in-page', checkAfterSettle)

    win.on('close', (event) => {
      event.preventDefault()
      finish()
    })

    win.loadURL(captchaUrl).catch(() => {
      writeFileSync(cookieFilePath, '# Netscape HTTP Cookie File\n', 'utf8')
      if (!done) { done = true; resolve({ cookieFile: cookieFilePath, streamHeaders: [] }) }
    })
  })
}

let mainWindow: BrowserWindow | null = null
let settingsStore: JsonStore<Settings>
let queue: DownloadQueue

function defaultSettings(): Settings {
  return {
    downloadDir: app.getPath('downloads'),
    concurrency: 1,
    autoStart: false,
    outputTemplate: '%(title)s [%(id)s].%(ext)s'
  }
}

function createWindow(): void {
  mainWindow = new BrowserWindow({
    width: 1120,
    height: 780,
    minWidth: 880,
    minHeight: 560,
    show: false,
    autoHideMenuBar: true,
    backgroundColor: '#0b0f17',
    title: 'Video Downloader',
    webPreferences: {
      preload: join(__dirname, '../preload/index.js'),
      sandbox: true,
      contextIsolation: true,
      nodeIntegration: false
    }
  })

  mainWindow.on('ready-to-show', () => mainWindow?.show())
  mainWindow.on('closed', () => {
    mainWindow = null
  })

  // Anything that wants a new window (a source link, say) opens in the real browser.
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    void shell.openExternal(url)
    return { action: 'deny' }
  })

  const devServerUrl = process.env['ELECTRON_RENDERER_URL']
  if (isDev && devServerUrl) {
    void mainWindow.loadURL(devServerUrl)
  } else {
    void mainWindow.loadFile(join(__dirname, '../renderer/index.html'))
  }
}

function send(channel: string, payload: unknown): void {
  if (mainWindow && !mainWindow.isDestroyed()) {
    mainWindow.webContents.send(channel, payload)
  }
}

function registerIpc(): void {
  ipcMain.handle('settings:get', () => settingsStore.get())

  ipcMain.handle('settings:set', (_event, patch: Partial<Settings>) => {
    const next: Partial<Settings> = {}
    if (typeof patch.downloadDir === 'string' && patch.downloadDir.trim()) {
      next.downloadDir = patch.downloadDir
    }
    if (typeof patch.concurrency === 'number') {
      next.concurrency = Math.min(5, Math.max(1, Math.round(patch.concurrency)))
    }
    if (typeof patch.autoStart === 'boolean') next.autoStart = patch.autoStart
    if (typeof patch.outputTemplate === 'string' && patch.outputTemplate.trim()) {
      next.outputTemplate = patch.outputTemplate.trim()
    }
    const updated = settingsStore.set(next)
    if (next.concurrency !== undefined) queue.refresh()
    return updated
  })

  ipcMain.handle('settings:choose-folder', async () => {
    if (!mainWindow) return null
    const result = await dialog.showOpenDialog(mainWindow, {
      title: 'Choose download folder',
      defaultPath: settingsStore.get().downloadDir,
      properties: ['openDirectory', 'createDirectory']
    })
    if (result.canceled || !result.filePaths[0]) return null
    return settingsStore.set({ downloadDir: result.filePaths[0] }).downloadDir
  })

  ipcMain.handle('queue:list', () => queue.list())
  ipcMain.handle('queue:add', (_event, text: string) => queue.add(text))
  ipcMain.handle('queue:remove', (_event, id: string) => queue.remove(id))
  ipcMain.handle('queue:start', (_event, id?: string) => queue.start(id))
  ipcMain.handle('queue:cancel', (_event, id: string) => queue.cancel(id))
  ipcMain.handle('queue:cancel-all', () => queue.cancelAll())
  ipcMain.handle('queue:clear-finished', () => queue.clearFinished())
  ipcMain.handle('queue:retry-metadata', (_event, id: string) => queue.retryMetadata(id))

  ipcMain.handle('binaries:info', () => getBinariesInfo())
  ipcMain.handle('binaries:update-ytdlp', () => updateYtDlp())

  ipcMain.handle('shell:reveal', (_event, filePath: string) => {
    shell.showItemInFolder(filePath)
  })
  ipcMain.handle('shell:open-path', (_event, target: string) => shell.openPath(target))
  ipcMain.handle('shell:open-external', (_event, url: string) => {
    if (/^https?:\/\//i.test(url)) void shell.openExternal(url)
  })

  ipcMain.handle('clipboard:read', () => clipboard.readText())

  ipcMain.handle('captcha:solve', async (_event, id: string) => {
    const item = queue.list().find((i) => i.id === id)
    if (!item?.captchaUrl) return

    // Headless extraction for VINOVO embeds — stage-1 API accepts empty reCAPTCHA.
    if (/vinovo\.to\/e\//i.test(item.captchaUrl)) {
      try {
        const vinovo = await fetchVinovoStream(item.captchaUrl)
        if (vinovo) {
          queue.retryWithStream(id, vinovo.streamUrl, undefined, vinovo.headers)
          return
        }
      } catch {
        // fall through to browser-window solver
      }
    }

    const cookieFilePath = join(app.getPath('userData'), `cookies-${id}.txt`)
    const result = await openCaptchaWindow(item.captchaUrl, cookieFilePath)
    if (result.streamUrl) {
      queue.retryWithStream(id, result.streamUrl, result.cookieFile, result.streamHeaders)
    } else {
      queue.retryWithCookies(id, result.cookieFile)
    }
  })
}

if (!app.requestSingleInstanceLock()) {
  app.quit()
} else {
  app.on('second-instance', () => {
    if (!mainWindow) return
    if (mainWindow.isMinimized()) mainWindow.restore()
    mainWindow.focus()
  })

  void app.whenReady().then(() => {
    settingsStore = new JsonStore<Settings>('settings.json', defaultSettings())
    queue = new DownloadQueue(() => settingsStore.get())
    queue.on('change', (items: QueueItem[]) => send('queue:changed', items))

    registerIpc()
    createWindow()

    app.on('activate', () => {
      if (BrowserWindow.getAllWindows().length === 0) createWindow()
    })
  })

  app.on('window-all-closed', () => {
    if (process.platform !== 'darwin') app.quit()
  })

  app.on('before-quit', () => {
    queue?.dispose()
    settingsStore?.flush()
  })
}
