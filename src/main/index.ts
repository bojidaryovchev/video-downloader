const isDev = !app.isPackaged

function writeNetscapeCookies(filePath: string, cookies: Cookie[]): void {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Video Downloader', '']
  for (const c of cookies) {
    if (!c.domain) continue
    const includeSubdomains = c.domain.startsWith('.') ? 'TRUE' : 'FALSE'
    const path = c.path ?? '/'
    const secure = c.secure ? 'TRUE' : 'FALSE'
    const expiry = c.expirationDate ? Math.floor(c.expirationDate) : 0
    lines.push([c.domain, includeSubdomains, path, secure, expiry, c.name, c.value].join('\t'))
  }
  writeFileSync(filePath, lines.join('\n'), 'utf8')
}

// Detects human-solvable CAPTCHA widgets still visible on the page.
const DETECT_CAPTCHA_JS = `
(function () {
  return !!(
    document.querySelector('iframe[src*="recaptcha"]') ||
    document.querySelector('iframe[src*="hcaptcha"]') ||
    document.querySelector('iframe[src*="challenges.cloudflare.com"]') ||
    document.querySelector('.g-recaptcha') ||
    document.querySelector('.h-captcha') ||
    document.querySelector('[data-sitekey]') ||
    document.querySelector('#challenge-form') ||
    document.querySelector('cf-turnstile') ||
    /just a moment/i.test(document.title)
  );
})()
`

// Finds the stream URL from the page DOM / player APIs after the page has rendered.
const FIND_STREAM_URL_JS = `
(function () {
  // Check all video elements (currentSrc is set once the player loads the source)
  for (const v of document.querySelectorAll('video')) {
    const src = v.currentSrc || v.src;
    if (src && /^https?:\\/\\//.test(src)) return src;
  }
  for (const s of document.querySelectorAll('video source')) {
    if (s.src && /^https?:\\/\\//.test(s.src)) return s.src;
  }
  // VideoJS 7/8 — try every known accessor
  try {
    if (window.videojs) {
      const all = typeof window.videojs.getAllPlayers === 'function'
        ? window.videojs.getAllPlayers()
        : Object.values(window.videojs.getPlayers ? window.videojs.getPlayers() : (window.videojs.players || {}));
      for (const p of all) {
        if (!p) continue;
        const src = typeof p.currentSrc === 'function' ? p.currentSrc()
                  : typeof p.src       === 'function' ? p.src() : null;
        if (src && /^https?:\\/\\//.test(src)) return src;
      }
    }
  } catch {}
  // JW Player
  try { const f = jwplayer().getPlaylistItem().file; if (f) return f; } catch {}
  // Scan inline scripts for m3u8/mpd URLs
  const re = /["'](https?:\\/\\/[^"']+\\.(?:m3u8|mpd)[^"']*)/i;
  for (const script of document.querySelectorAll('script:not([src])')) {
    const m = re.exec(script.textContent || '');
    if (m) return m[1];
  }
  return null;
})()
`

/** Recursively finds the first video stream URL inside a parsed JSON value. */
function findStreamUrlInJson(obj: unknown, depth = 0): string | undefined {
  if (depth > 10) return undefined
  if (typeof obj === 'string') {
    return /^https?:\/\/.+\.(m3u8|mpd|mp4|webm)(\?|$)/i.test(obj) ? obj : undefined
  }
  if (Array.isArray(obj)) {
    for (const v of obj) { const r = findStreamUrlInJson(v, depth + 1); if (r) return r }
  } else if (obj && typeof obj === 'object') {
    for (const v of Object.values(obj as Record<string, unknown>)) {
      const r = findStreamUrlInJson(v, depth + 1); if (r) return r
    }
  }
  return undefined
}

